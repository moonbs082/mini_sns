/**
 * id 로 운동 찾기
 * @param {string} exerciseId - 운동 id
 * @returns {object | undefined}
 */
export function findExercise(exerciseId) {
  return EXERCISES.find((exercise) => exercise.id === exerciseId);
}

/**
 * 키우고 싶은 부위에 맞는 추천 운동
 * @param {string[]} targetParts - 부위 값 목록
 * @returns {object[]}
 */
export function recommendExercises(targetParts) {
  if (!targetParts || targetParts.length === 0) {
    return EXERCISES.slice(0, 3);
  }
  return EXERCISES.filter((exercise) => exercise.parts.some((part) => targetParts.includes(part)));
}
